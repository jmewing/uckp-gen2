#!/bin/bash
# fbwrite.sh — render text onto the UCKP 160x60 RGB565 SPI panel (fb_sp8110).
# Takes over /dev/fb0, so it must stop the UniFi UI first.
#
#   systemctl stop ck-ui        # free the framebuffer
#   ./fbwrite.sh "192.168.1.10" "srv ok"
#   systemctl start ck-ui       # restore the stock UI
#
# Panel: 160x60 px, 16 bpp RGB565, rotate=180 (handled below),
#        framebuffer = 160*60*2 = 19200 bytes.
set -euo pipefail

FB=/dev/fb0
W=160; H=60

# --- 5x7 bitmap font (subset: 0-9 . : / A-Z a-z space) ---
# Represent each glyph as 7 rows; we only need digits, '.', ':', '/', '-', and
# common letters for an IP + short status line. Extend as needed.
# (Kept compact: a real deployment should embed a full font.)

command -v python3 >/dev/null || { echo "python3 required"; exit 1; }

[ -w "$FB" ] || { echo "$FB not writable (is ck-ui still running?)"; exit 2; }

exec python3 - "$FB" "$W" "$H" "$@" <<'PY'
import sys, mmap, struct
fb_path, W, H = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
lines = sys.argv[4:] or ["UCK-G2", "no text"]

