def up(c): return c.upper() if c.upper() in FONT else ' '

# build a W*H RGB565 framebuffer (RGB565 little-endian)
buf = bytearray(W*H*2)
def px(x,y,on):
    if 0<=x<W and 0<=y<H:
        # rotate 180
        rx, ry = W-1-x, H-1-y
        v = 0xFFFF if on else 0x0000
        o = (ry*W+rx)*2
        buf[o] = v & 0xFF; buf[o+1] = v >> 8

# draw lines (5x7 font, 1px gap -> 6px cell)
y = 2
for ln in lines:
    x = 2
    for ch in ln:
        rows = FONT[up(ch)]
        for ry in range(7):
            for rx in range(5):
                if rows[ry][rx] == '1':
                    px(x+rx, y+ry, True)
        x += 6
        if x > W-6: break
    y += 9
    if y > H-8: break

with open(fb_path,'r+b') as f:
    mm = mmap.mmap(f.fileno(), W*H*2)
    mm.seek(0); mm.write(bytes(buf)); mm.flush(); mm.close()
print("wrote %d bytes to %s" % (len(buf), fb_path))
